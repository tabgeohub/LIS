import assert from "node:assert/strict";
import { generateKeyPairSync } from "node:crypto";
import { canonicalJson, FlightMigrationExportV1, signExport, verifyExport } from "./exportContract";
import { matchGeometry, matchPoint, MatchPoint } from "./matching";
import { missingRequiredColumns, REQUIRED_COLUMNS } from "./schemaPreflight";

const now = Date.parse("2026-01-01T12:00:00Z");
const keys = generateKeyPairSync("ed25519");
const privateKey = keys.privateKey.export({ type: "pkcs8", format: "pem" }).toString();
const publicKey = keys.publicKey.export({ type: "spki", format: "pem" }).toString();
const payload: FlightMigrationExportV1 = { version: 1, source: { instance: "instance", environment: "TST", issuer: "issuer", flightId: "1" }, exportId: "export", createdAt: new Date(now).toISOString(), expiresAt: new Date(now + 1000).toISOString(), exportedBy: { subject: "source-admin", issuer: "issuer" }, records: { flight: { id: 1 }, points: [], geometries: [], completions: [], attachments: [], path: null, logs: [] }, counts: { points: 0, geometries: 0, completions: 0, attachments: 0, logs: 0 } };
assert.equal(canonicalJson({ z: 1, a: [2, 1] }), '{"a":[2,1],"z":1}');
const signed = signExport(payload, "key", privateKey, now);
assert.equal(verifyExport(signed, { key: publicKey }, now), payload);
assert.throws(() => verifyExport({ ...signed, payload: { ...payload, exportId: "other" } }, { key: publicKey }, now), /INVALID_EXPORT_SIGNATURE/);
assert.throws(() => verifyExport(signed, { key: publicKey }, now + 1000), /EXPORT_EXPIRED/);
assert.throws(() => verifyExport(signed, {}, now), /UNKNOWN_SIGNING_KEY/);
assert.throws(() => signExport({ ...payload, counts: { ...payload.counts, points: 1 } }, "key", privateKey, now), /INVALID_EXPORT_COUNTS/);
assert.throws(() => signExport({ ...payload, records: { ...payload.records, flight: { password: "secret" } } }, "key", privateKey, now), /SENSITIVE_EXPORT_FIELD/);
const p: MatchPoint = { id: "1", name: " é ", region: "A", latitude: 1, longitude: 2, rdX: 3, rdY: 4, geometryId: null };
assert.equal(matchPoint(p, [{ ...p, id: "99", name: "e\u0301" }], "A").kind, "reuse");
assert.equal(matchPoint(p, [{ ...p, name: "different" }], "A").kind, "create");
assert.equal(matchPoint(p, [{ ...p, region: "B" }], "A").kind, "conflict");
assert.equal(matchPoint(p, [p, p], "A").kind, "conflict");
assert.equal(matchPoint({ ...p, latitude: NaN }, [], "A").kind, "conflict");
const g = { id: "1", name: "geometry", region: "A", type: "line", vertices: [p, { ...p, name: "second" }] };
assert.equal(matchGeometry(g, [{ ...g, id: "2" }], "A").kind, "reuse");
assert.equal(matchGeometry(g, [{ ...g, vertices: [...g.vertices].reverse() }], "A").kind, "conflict");
const columns = Object.entries(REQUIRED_COLUMNS).flatMap(([table_name, names]) => names.map(column_name => ({ table_name, column_name })));
assert.deepEqual(missingRequiredColumns(columns), []);
assert.deepEqual(missingRequiredColumns(columns.filter(c => c.column_name !== "finished_at")), ["finished_plans.finished_at"]);
