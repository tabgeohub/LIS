import assert from "node:assert/strict";
import { migrationConfig, configuredForDestination, configuredForSource } from "./config";
import { regionNames } from "./destination";

const disabled = migrationConfig({ enabled: false });
assert.equal(disabled.enabled, false);
assert.equal(configuredForSource(disabled), false);
assert.equal(configuredForDestination(disabled), false);
const source = migrationConfig({ enabled: true, role: "source", sourceInstance: "11111111-1111-4111-8111-111111111111", destinationFrontendUrl: "https://prod.example/", exportKeyId: "first", exportPrivateKey: "key", exportReadCredential: "read" });
assert.equal(configuredForSource(source), true);
assert.equal(configuredForDestination(source), false);
const destination = migrationConfig({ enabled: true, role: "destination", sourceInstance: "11111111-1111-4111-8111-111111111111", sourceBackendUrl: "https://tst.example/", destinationRegions: ["RWS A", "admin", "Unknown"], exportReadCredential: "read", statusReadCredential: "status", arcgisAllowedOrigins: ["https://arcgis.example"], trustedPublicKeys: { first: "public" } });
assert.equal(configuredForDestination(destination), true);
assert.deepEqual(regionNames([{ id: "RWS A" }, { id: "admin" }, { id: "Other" }], destination.destinationRegions), ["RWS A"]);
assert.equal(migrationConfig("unknown.example").role, "source");
assert.equal(migrationConfig("tst-lis.rws.nl").enabled, false);
assert.equal(migrationConfig("lis.rws.nl").enabled, false);
assert.equal(migrationConfig("unknown.example").enabled, false);
assert.equal(migrationConfig("localhost").enabled, true);
assert.equal(migrationConfig("localhost").readOnly, true);
assert.equal(configuredForSource(migrationConfig("localhost")), true);
